// For Loop
console.log("Table of 18:");
for (let i = 1; i <= 10; i++) {
      console.log(18, " X ", i, " = ", 18 * i);
}

// While Loop
console.log("Table of 10:")
let j = 1;
while (j <= 10) {
      console.log(10, " X ", j, " = ", 10 * j);
      j++;
}

// Do While Loop
console.log("Table of 5:")
let k = 1;
do {
      console.log(5, " X ", k, " = ", 5 * k);
      k++;
} while (k <= 10);